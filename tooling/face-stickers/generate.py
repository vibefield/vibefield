"""Build and verify the 48-face After Hours collection against the live emoji deck."""
from pathlib import Path
import argparse, html, io, json, re, subprocess, sys, zipfile
from art import faces

ROOT=Path(__file__).resolve().parents[2]
ATTRS={'strokeWidth':'stroke-width','strokeLinecap':'stroke-linecap','strokeLinejoin':'stroke-linejoin','fillRule':'fill-rule'}
def svg(face,optical='large',finish='sticker',title=True):
    grid=112 if optical=='large' else 56
    def shapes(under=False):
        output=[]
        for node in face[optical]:
            attrs=node['attrs'].copy()
            if under:attrs.update(fill='#fff',stroke='#fff',strokeWidth=10 if optical=='large' else 8,strokeLinecap='round',strokeLinejoin='round')
            values=' '.join(f'{ATTRS.get(k,k)}="{html.escape(str(v),quote=True)}"' for k,v in attrs.items())
            output.append(f'<{node["tag"]} {values}/>')
        return ''.join(output)
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {grid} {grid}" fill="currentColor" color="#171815" stroke="none">'
       +(f'<title>{html.escape(face["label"])} — {html.escape(face["nickname"])} ({optical})</title>' if title else '')
       +(shapes(True) if finish=='sticker' else '')+shapes()+'</svg>')

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true')
    parser.add_argument('--root',type=Path,default=ROOT,help='Repository containing the live FACE_DECK and Biome.')
    parser.add_argument('--out',type=Path,help='Optional staging output directory.')
    args=parser.parse_args();root=args.root;out=args.out or root
    policy=(root/'packages/contracts/src/user-face.ts').read_text()
    match=re.search(r'export const FACE_DECK = \[(.*?)\] as const;',policy,re.S)
    if not match:raise ValueError('Could not locate FACE_DECK; review the changed policy source.')
    deck=re.findall(r'"([^"]+)"',match[1])
    key=lambda value:re.sub('[\ufe0e\ufe0f]','',value)
    assert [f['emoji'] for f in faces]==deck,'FACE_DECK changed: redraw/review coverage and deck order.'
    assert len(faces)==len({f['id'] for f in faces})==len({key(f['emoji']) for f in faces})==48
    # A browser may silently truncate a malformed path; fail before exporting it.
    arity={'M':2,'L':2,'H':1,'V':1,'C':6,'S':4,'Q':4,'T':2,'A':7,'Z':0}
    number=r'[-+]?(?:\d*\.\d+|\d+\.?\d*)(?:[eE][-+]?\d+)?'
    for face in faces:
        for optical in ['large','small']:
            for shape in face[optical]:
                if shape['tag']!='path':continue
                d=shape['attrs']['d']
                chunks=re.findall(r'([MmLlHhVvCcSsQqTtAaZz])([^MmLlHhVvCcSsQqTtAaZz]*)',d)
                assert chunks and ''.join(a+b for a,b in chunks)==d,(face['id'],optical,d)
                for command,coords in chunks:
                    values=re.findall(number,coords);size=arity[command.upper()]
                    assert not re.sub(number+r'|[\s,]','',coords),(face['id'],command,coords)
                    assert (not values if size==0 else len(values)>=size and len(values)%size==0),(face['id'],optical,command,coords)
    emitted={};mismatch=[]
    def write(rel,data):
        raw=data.encode() if isinstance(data,str) else data;emitted[rel]=raw;dest=out/rel
        if dest.exists() and dest.read_bytes()==raw:return
        if args.check:mismatch.append(rel);return
        dest.parent.mkdir(parents=True,exist_ok=True);dest.write_bytes(raw)
    names=json.dumps([f['id'] for f in faces])
    schema='''export const FACE_STICKER_IDS = NAMES as const;
export type FaceStickerId = (typeof FACE_STICKER_IDS)[number];
export type FaceStickerGroup = "Animals" | "Garden" | "Food" | "Objects";
export type FaceStickerOptical = "large" | "small";
export interface FaceStickerShape { tag: "path" | "circle" | "ellipse" | "rect"; attrs: Readonly<Record<string, string | number>>; }
export interface FaceStickerDrawing {
 id: FaceStickerId; emoji: string; label: string; nickname: string; group: FaceStickerGroup;
 idea: string; smallNote: string; large: readonly FaceStickerShape[]; small: readonly FaceStickerShape[];
}
'''.replace('NAMES',names)
    source='// Generated by tooling/face-stickers/generate.py. Original After Hours artwork.\n'+schema+'export const FACE_STICKERS: Record<FaceStickerId, FaceStickerDrawing> = '+json.dumps({f['id']:f for f in faces},ensure_ascii=False,indent=2)+';\n'
    formatted=subprocess.run([str(root/'node_modules/.bin/biome'),'format','--stdin-file-path=packages/design-kit/src/face-stickers/data.ts'],input=source,text=True,capture_output=True,check=True,cwd=root).stdout
    write('packages/design-kit/src/face-stickers/data.ts',formatted)
    metadata=json.dumps(faces,ensure_ascii=False,indent=2)+'\n'
    write('packages/design-kit/src/face-stickers/catalogue.json',metadata)
    files={'catalogue.json':metadata}
    for optical in ['large','small']:
        symbols=[]
        for face in faces:
            for finish in ['sticker','artwork']:
                name=f'{optical}/{finish}/{face["id"]}.svg';files[name]=svg(face,optical,finish)+'\n'
                write('packages/design-kit/assets/face-stickers/'+name,files[name])
            symbol=svg(face,optical,'artwork',False).replace('<svg xmlns="http://www.w3.org/2000/svg"',f'<symbol id="vf-face-{optical}-{face["id"]}"',1).replace('</svg>','</symbol>')
            symbols.append(symbol)
        name=f'{optical}/sprite.svg';files[name]='<svg xmlns="http://www.w3.org/2000/svg">'+''.join(symbols)+'</svg>\n'
        write('packages/design-kit/assets/face-stickers/'+name,files[name])
    files['README.md']=(out/'packages/design-kit/assets/face-stickers/README.md').read_text()
    archive=io.BytesIO()
    with zipfile.ZipFile(archive,'w',compression=zipfile.ZIP_DEFLATED,compresslevel=9) as z:
        for name,content in sorted(files.items()):
            info=zipfile.ZipInfo('vibefield-face-club/'+name,date_time=(2026,9,22,0,0,0))
            info.compress_type=zipfile.ZIP_DEFLATED;info.external_attr=0o644<<16
            z.writestr(info,content.encode(),compresslevel=9)
    write('docs/design/vibefield-face-club.zip',archive.getvalue())
    if mismatch:
        print('Generated files differ:\n'+'\n'.join(mismatch),file=sys.stderr);raise SystemExit(1)
    print(('Verified' if args.check else 'Generated')+' FACE CLUB: all 48 deck emoji, 96 optical drawings, 192 SVGs, 2 sprites, and ZIP.')
if __name__=='__main__':main()
