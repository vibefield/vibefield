#!/usr/bin/env node
// Emits the chrome glyph set from `drawings.mjs` + `picks.json`:
//   packages/design-kit/src/glyphs/data.ts          — the kit's typed drawings
//   apps/ios/…/FieldDesign/Resources/FieldGlyphs.xcassets — template SVGs for the phone
// `--check` regenerates in memory and fails if any committed output differs.

import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { DRAWINGS, GLYPH_NAMES } from "./drawings.mjs";

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, "..", "..");
const PICKS = JSON.parse(readFileSync(join(HERE, "picks.json"), "utf8"));
const DATA_TS = join(ROOT, "packages/design-kit/src/glyphs/data.ts");
const XCASSETS = join(
  ROOT,
  "apps/ios/VibeFieldKit/Sources/FieldDesign/Resources/FieldGlyphs.xcassets",
);

const check = process.argv.includes("--check");

/** `<path d="…"/>`, `<circle …/>`, `<rect …/>` fragments → [tag, attrs] tuples. */
function shapes(markup) {
  const out = [];
  for (const m of markup.matchAll(/<(path|circle|rect)\s+([^>]*?)\/>/g)) {
    const attrs = {};
    for (const a of m[2].matchAll(/([\w-]+)="([^"]*)"/g)) attrs[a[1]] = a[2];
    out.push([m[1], attrs]);
  }
  return out;
}

function pickOf(name) {
  return PICKS.hardware.includes(name) ? "hardware" : "instrument";
}

/* ── data.ts ── */
function dataTs() {
  const lines = [];
  lines.push(
    "// GENERATED by tooling/glyphs/build.mjs from drawings.mjs + picks.json — do not edit.",
  );
  lines.push("// DESIGN.md §13: one 24-unit box, currentColor only, no masks or filters.");
  lines.push("");
  lines.push(
    'export type GlyphShape = readonly [tag: "path" | "circle" | "rect", attrs: Readonly<Record<string, string>>];',
  );
  lines.push("export interface InstrumentGlyph {");
  lines.push('  readonly kind: "instrument";');
  lines.push("  readonly strokes: readonly GlyphShape[];");
  lines.push("  readonly fills: readonly GlyphShape[];");
  lines.push("  readonly transform?: string;");
  lines.push("}");
  lines.push("export interface HardwareGlyph {");
  lines.push('  readonly kind: "hardware";');
  lines.push("  /** One evenodd path: bodies and their holes in a single `d`. */");
  lines.push("  readonly d: string;");
  lines.push("}");
  lines.push("export type GlyphDrawing = InstrumentGlyph | HardwareGlyph;");
  lines.push("export interface GlyphMeta {");
  lines.push("  readonly label: string;");
  lines.push('  readonly group: "actions" | "navigation" | "objects" | "signals" | "studio";');
  lines.push("  readonly role: string;");
  lines.push("}");
  lines.push("");
  lines.push(`export const GLYPH_NAMES = ${JSON.stringify(GLYPH_NAMES)} as const;`);
  lines.push("export type GlyphName = (typeof GLYPH_NAMES)[number];");
  lines.push("");
  lines.push("export const GLYPH_META: Readonly<Record<GlyphName, GlyphMeta>> = {");
  for (const name of GLYPH_NAMES) {
    const g = DRAWINGS[name];
    lines.push(`  ${name}: ${JSON.stringify({ label: g.label, group: g.group, role: g.role })},`);
  }
  lines.push("};");
  lines.push("");
  lines.push("export const GLYPHS: Readonly<Record<GlyphName, GlyphDrawing>> = {");
  for (const name of GLYPH_NAMES) {
    const g = DRAWINGS[name];
    if (pickOf(name) === "hardware") {
      lines.push(`  ${name}: { kind: "hardware", d: ${JSON.stringify(g.hardware.d)} },`);
    } else {
      const i = g.instrument;
      const entry = {
        kind: "instrument",
        strokes: shapes(i.s ?? ""),
        fills: shapes(i.f ?? ""),
        ...(i.tf ? { transform: i.tf } : {}),
      };
      lines.push(`  ${name}: ${JSON.stringify(entry)},`);
    }
  }
  lines.push("};");
  lines.push("");
  return `${lines.join("\n")}`;
}

/* ── iOS template SVGs ── */
function svgOf(name) {
  const g = DRAWINGS[name];
  if (pickOf(name) === "hardware") {
    return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" width="24" height="24"><path fill="black" fill-rule="evenodd" d="${g.hardware.d}"/></svg>\n`;
  }
  const i = g.instrument;
  const open = i.tf ? `<g transform="${i.tf}">` : "";
  const close = i.tf ? "</g>" : "";
  const strokes = i.s
    ? `<g fill="none" stroke="black" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${i.s}</g>`
    : "";
  const fills = i.f ? `<g fill="black">${i.f}</g>` : "";
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" width="24" height="24">${open}${strokes}${fills}${close}</svg>\n`;
}
const IMAGESET_CONTENTS = (name) =>
  `${JSON.stringify(
    {
      images: [{ filename: `${name}.svg`, idiom: "universal" }],
      info: { author: "xcode", version: 1 },
      properties: {
        "preserves-vector-representation": true,
        "template-rendering-intent": "template",
      },
    },
    null,
    2,
  )}\n`;
const CATALOG_CONTENTS = `${JSON.stringify({ info: { author: "xcode", version: 1 } }, null, 2)}\n`;

function iosFiles() {
  const files = new Map();
  files.set(join(XCASSETS, "Contents.json"), CATALOG_CONTENTS);
  for (const name of PICKS.ios) {
    if (!DRAWINGS[name]) throw new Error(`picks.json names an unknown glyph: ${name}`);
    files.set(
      join(XCASSETS, `glyph-${name}.imageset`, "Contents.json"),
      IMAGESET_CONTENTS(`glyph-${name}`),
    );
    files.set(join(XCASSETS, `glyph-${name}.imageset`, `glyph-${name}.svg`), svgOf(name));
  }
  return files;
}

/* ── run ── */
for (const name of PICKS.hardware) {
  if (!DRAWINGS[name]) throw new Error(`picks.json names an unknown glyph: ${name}`);
}
const outputs = new Map([[DATA_TS, dataTs()], ...iosFiles()]);
let stale = 0;
for (const [path, content] of outputs) {
  const current = existsSync(path) ? readFileSync(path, "utf8") : null;
  if (current === content) continue;
  stale++;
  if (check) {
    console.error(`stale: ${path}`);
  } else {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, content);
    console.log(`wrote ${path}`);
  }
}
if (check) {
  if (stale) {
    console.error(`${stale} generated file(s) out of date — run node tooling/glyphs/build.mjs`);
    process.exit(1);
  }
  console.log(
    `glyphs fresh: ${GLYPH_NAMES.length} names, ${PICKS.hardware.length} hardware, ${PICKS.ios.length} on iOS`,
  );
} else if (!stale) {
  console.log("glyphs already fresh");
}
