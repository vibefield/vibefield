import { encodeIcns, encodeIco, utf8, zipStore } from "./formats.mjs";
import { LIVING } from "./living-assets.mjs";
import { PLATFORMS, slug } from "./model.mjs";

const INFO = { author: "xcode", version: 1 };
const WINDOWS_SIZES = [16, 20, 24, 32, 40, 48, 64, 96, 128, 256];
const LINUX_SIZES = [16, 24, 32, 48, 64, 96, 128, 256, 512, 1024];
const MAC_REPRESENTATIONS = [
  { points: 16, scale: 1, type: "icp4" },
  { points: 16, scale: 2, type: "ic11" },
  { points: 32, scale: 1, type: "icp5" },
  { points: 32, scale: 2, type: "ic12" },
  { points: 128, scale: 1, type: "ic07" },
  { points: 128, scale: 2, type: "ic13" },
  { points: 256, scale: 1, type: "ic08" },
  { points: 256, scale: 2, type: "ic14" },
  { points: 512, scale: 1, type: "ic09" },
  { points: 512, scale: 2, type: "ic10" },
];
const STATES = ["ready", "update", "attention", "offline"];
const json = (value) => `${JSON.stringify(value, null, 2)}\n`;
const xml = (value) =>
  String(value).replace(
    /[&<>"']/g,
    (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&apos;" })[c],
  );

function abortIfRequested(signal) {
  if (signal?.aborted) throw signal.reason ?? new DOMException("Export cancelled", "AbortError");
}

function base64(bytes) {
  let binary = "";
  for (let offset = 0; offset < bytes.length; offset += 32768) {
    binary += String.fromCharCode(...bytes.subarray(offset, offset + 32768));
  }
  return btoa(binary);
}

function embeddedRasterSvg(data, name) {
  return `<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="0 0 1024 1024"><title>${xml(name)}</title><!-- Raster-backed SVG: the procedural dust field is a 1024px PNG, not vector geometry. --><image width="1024" height="1024" href="data:image/png;base64,${base64(data)}"/></svg>\n`;
}

function composerColor(hex) {
  const rgb = [1, 3, 5].map((at) => Number.parseInt(hex.slice(at, at + 2), 16) / 255);
  return `extended-srgb:${rgb.map((n) => n.toFixed(5)).join(",")},1.00000`;
}

function composerLayer(name, light, dark) {
  return {
    glass: false,
    "image-name-specializations": [
      { value: light },
      { appearance: "dark", value: dark },
      { appearance: "tinted", value: dark },
    ],
    name,
    position: { scale: 1, "translation-in-points": [0, 0] },
  };
}

function composerDefinition(recipe) {
  // Icon Composer serializes front-to-back. An opaque field first hides the ribbon.
  const layers = [composerLayer("Living ribbon", "mark-light.svg", "mark-dark.svg")];
  if (recipe.style === "dust")
    layers.push(composerLayer("Wormhole field", "field-light.png", "field-dark.png"));
  return {
    "fill-specializations": [
      { value: { solid: composerColor(recipe.lightGround) } },
      { appearance: "dark", value: { solid: composerColor(recipe.darkGround) } },
    ],
    groups: [
      {
        layers,
        shadow: { kind: "none", opacity: 0.5 },
        translucency: { enabled: false, value: 0.5 },
      },
    ],
    "supported-platforms": { circles: [], squares: "shared" },
  };
}

function readme(recipe, targets, name) {
  return `# ${recipe.name || "VibeField"} icon bundle

Generated by VibeField Icon Studio. Recipe version: ${recipe.version}. Artwork: ${recipe.style}; selected appearance: ${recipe.appearance}. Targets: ${targets.join(", ")}.

The bundled recipe.json is the source of these exports. Reimport it into the studio to reproduce or adjust this set. Static platform icons use the recipe's pose and frozen time; the original living SVGs are clearly named and remain the shipping design-kit animations, independent of this recipe's edits.

## macOS

Open macos/${name}.icon in Apple's Icon Composer. It contains unmasked vector mark layers, light/dark appearance specializations, and, for a dust recipe, separate full-bleed raster field layers. Add the .icon package to Xcode and select its name as the app icon. Xcode compiles the platform effects and Assets.car; this ZIP does not claim to contain that native compiled catalog.

The light and dark .icns files and .iconset folders are conventional masked and padded fallbacks. Every set includes the ten standard point-size/scale representations, preserving separate optical rendering for e.g. 16pt@2x and 32pt@1x. To rebuild a fallback with Apple's utility:

    iconutil -c icns macos/${name}-light.iconset -o macos/${name}-light-native.icns

To inspect the browser-generated ICNS:

    iconutil -c iconset macos/${name}-light.icns -o /tmp/${name}-icon-check.iconset

Use the native Icon Composer/Xcode rendition for a modern packaged app; ICNS is a fallback, not a replacement for native compilation. macOS optical padding is a studio treatment. Review in Icon Composer and on the target OS before shipping.

## Windows and Linux

windows/${name}.ico contains PNG-backed entries at ${WINDOWS_SIZES.join(", ")} px for current Windows. MSIX-specific store tiles are not included. Linux assets follow hicolor/{size}x{size}/apps/${name}.png plus hicolor/scalable/apps/${name}.svg. A plain recipe has a vector SVG; a dust recipe's scalable SVG embeds its 1024px PNG and is labelled as raster-backed in export-manifest.json. Install under your application's share/icons path; use Icon=${name} in its .desktop entry.

## iOS and iPadOS

ios/Assets.xcassets/AppIcon.appiconset contains 1024px default, dark, and tinted appearances with Contents.json. These exports use RGB PNGs without an alpha channel and full-bleed square backgrounds; Xcode and iOS apply the mask. This is the studio's opaque three-appearance family. Tinted art is grayscale for system tinting. Import the asset catalog into the app target and use AppIcon. For Liquid Glass, use the .icon source from the macOS target with Xcode instead of treating PNGs as layered artwork.

## visionOS

visionos/Assets.xcassets/AppIcon.solidimagestack is a two-layer 1024px Xcode image stack. Front is the complete transparent ribbon, inset for circular masking; Back is the opaque field. The layers array is front-to-back, and each Content.imageset uses idiom vision and scale 2x. No circular crop or baked parallax is applied to the source layers. Xcode creates the compiled icon and the OS supplies masking and depth. Import into a visionOS app and select AppIcon; preview the resulting stack in Xcode before distribution.

## Menu bar and system tray

macOS template PNGs contain black pixels and alpha only. Four states (ready, update, attention, offline) are provided at 16, 18, and 22 points, each at 1x and 2x. These are sizing choices, not three different system requirements. Set NSImage.isTemplate = true, or Electron nativeImage.setTemplateImage(true); set the image's logical size to the chosen point size. Both files in each @2x pair must remain together. Standard names ending Template are used. Do not flatten template images onto a background.

Windows ICO and Linux PNG tray variants are exported separately for light and dark surfaces; choose the matching appearance at runtime. Template states use shape changes: update is a plain dot, attention a cut-out exclamation, offline a cut-out bar. State meaning must also be supplied in accessible labels/tooltips.

## Website

Copy web/ into the website's public assets, adapting the paths in web/head.html. favicon.ico contains 16,32,48px; favicon.svg adapts to light/dark browser chrome. The PNG fallbacks are fixed to the recipe's selected appearance. apple-touch-icon.png is an opaque, unmasked 180px square.

The web app manifest contains distinct 192/512px any and maskable entries. Maskable images are opaque squares with important artwork inset inside the centered circle whose diameter is 80% of the canvas. Adapt manifest name, start_url, id and scope to the actual app's deployed base path; a manifest and icons alone do not implement offline functionality. safari-pinned-tab.svg is a monochrome transparent 16-unit SVG mask.

## Validation and specifications

export-manifest.json records each file, dimensions where applicable, and format/alpha intent. Archive generation verifies unique safe paths and image container dimensions. Native integration, App Store validation and accessibility labels remain part of each app's build.

- Apple app icon design: https://developer.apple.com/design/human-interface-guidelines/app-icons
- Apple Icon Composer: https://developer.apple.com/documentation/xcode/creating-your-app-icon-using-icon-composer
- Apple asset catalogs: https://developer.apple.com/documentation/xcode/configuring-your-app-icon
- Apple template images: https://developer.apple.com/documentation/appkit/nsimage/istemplate
- Windows icon construction: https://learn.microsoft.com/en-us/windows/apps/design/iconography/app-icon-construction
- Linux icon theme layout: https://specifications.freedesktop.org/icon-theme/
- PWA maskable icons: https://developer.mozilla.org/en-US/docs/Web/Progressive_web_apps/How_to/Define_app_icons
- Safari pinned masks: https://developer.apple.com/library/archive/documentation/AppleApplications/Reference/SafariWebContent/pinnedTabs/pinnedTabs.html
`;
}

/** Build downloadable sources and platform files; it never writes into the app's shipping assets.
 * onProgress receives {done, total, label, files}; done/total counts finished platform targets.
 * The renderer owns art, optical tuning, alpha enforcement and all SVG geometry.
 */
export async function buildBundle(
  recipe,
  renderer,
  { targets = recipe.targets, onProgress = () => {}, signal } = {},
) {
  if (!recipe || recipe.version !== 1)
    throw new Error("An icon-studio version 1 recipe is required.");
  if (!Array.isArray(targets)) throw new TypeError("Export targets must be an array.");
  const known = new Set(PLATFORMS.map((platform) => platform.id));
  const selected = [...new Set(targets)];
  for (const target of selected)
    if (!known.has(target)) throw new Error(`Unknown export target: ${target}`);
  if (!selected.length) throw new Error("Select at least one export target.");
  if (typeof renderer?.png !== "function" || typeof renderer?.svg !== "function")
    throw new TypeError("Export needs PNG and SVG renderers.");
  const source = JSON.parse(JSON.stringify(recipe));
  source.targets = selected;
  const name = slug(source.name);
  const files = [];
  const assets = [];
  const used = new Set();
  let done = 0;
  const progress = (label) =>
    onProgress({ done, total: selected.length, label, files: files.length });
  const add = (path, data, meta = {}) => {
    abortIfRequested(signal);
    if (used.has(path)) throw new Error(`Duplicate export file: ${path}`);
    used.add(path);
    files.push({ name: path, data });
    assets.push({
      path,
      format: path.split(".").at(-1),
      bytes: typeof data === "string" ? utf8(data).length : data.byteLength,
      ...meta,
    });
    return data;
  };
  const addJson = (path, value) => add(path, json(value));
  const svg = (path, options, meta = {}) =>
    add(path, renderer.svg(source, options), { format: "svg", ...meta });
  const png = async (path, size, options = {}, meta = {}) => {
    abortIfRequested(signal);
    progress(path);
    abortIfRequested(signal);
    const data = await renderer.png(source, size, {
      appearance: source.appearance,
      shape: "square",
      layer: "composite",
      purpose: "app",
      opaque: false,
      ...options,
    });
    abortIfRequested(signal);
    return add(path, data, { width: size, height: size, alpha: !options.opaque, ...meta });
  };
  const appearance = source.appearance;

  for (const target of selected) {
    abortIfRequested(signal);
    progress(`Preparing ${PLATFORMS.find((p) => p.id === target).name}`);
    if (target === "macos") {
      const composerRoot = `macos/${name}.icon`;
      for (const ground of ["light", "dark"]) {
        svg(
          `${composerRoot}/Assets/mark-${ground}.svg`,
          { size: 1024, appearance: ground, layer: "mark", purpose: "app" },
          { width: 1024, height: 1024, alpha: true, vector: true },
        );
        if (source.style === "dust")
          await png(`${composerRoot}/Assets/field-${ground}.png`, 1024, {
            appearance: ground,
            layer: "background",
            opaque: true,
          });
        const icns = [];
        for (const { points, scale, type } of MAC_REPRESENTATIONS) {
          const size = points * scale;
          const data = await png(
            `macos/${name}-${ground}.iconset/icon_${points}x${points}${scale === 2 ? "@2x" : ""}.png`,
            size,
            { appearance: ground, shape: "macos", pointSize: points },
          );
          icns.push({ type, data });
        }
        add(`macos/${name}-${ground}.icns`, encodeIcns(icns), {
          representations: MAC_REPRESENTATIONS.map(({ points, scale }) => ({
            points,
            scale,
            pixels: points * scale,
          })),
        });
      }
      addJson(`${composerRoot}/icon.json`, composerDefinition(source));
    }

    if (target === "windows") {
      const entries = [];
      for (const size of WINDOWS_SIZES)
        entries.push({
          size,
          data: await png(`windows/png/${name}-${size}.png`, size, { shape: "tile" }),
        });
      add(`windows/${name}.ico`, encodeIco(entries), { sizes: WINDOWS_SIZES });
      await png(`windows/${name}-1024.png`, 1024, { shape: "tile" });
    }

    if (target === "linux") {
      let largest;
      for (const size of LINUX_SIZES)
        largest = await png(`linux/hicolor/${size}x${size}/apps/${name}.png`, size, {
          shape: "tile",
        });
      if (source.style === "dust")
        add(`linux/hicolor/scalable/apps/${name}.svg`, embeddedRasterSvg(largest, source.name), {
          width: 1024,
          height: 1024,
          vector: false,
          embeddedRaster: true,
        });
      else
        svg(
          `linux/hicolor/scalable/apps/${name}.svg`,
          { size: 1024, appearance, shape: "tile", layer: "composite", purpose: "app" },
          { width: 1024, height: 1024, vector: true },
        );
    }

    if (target === "ios") {
      const root = "ios/Assets.xcassets";
      addJson(`${root}/Contents.json`, { info: INFO });
      const images = [];
      for (const ground of ["light", "dark", "tinted"]) {
        const filename =
          ground === "light"
            ? "AppIcon.png"
            : `AppIcon-${ground === "dark" ? "Dark" : "Tinted"}.png`;
        await png(`${root}/AppIcon.appiconset/${filename}`, 1024, {
          appearance: ground,
          opaque: true,
        });
        images.push({
          filename,
          idiom: "universal",
          platform: "ios",
          size: "1024x1024",
          ...(ground === "light"
            ? {}
            : { appearances: [{ appearance: "luminosity", value: ground }] }),
        });
      }
      addJson(`${root}/AppIcon.appiconset/Contents.json`, { images, info: INFO });
    }

    if (target === "visionos") {
      const root = "visionos/Assets.xcassets";
      const stack = `${root}/AppIcon.solidimagestack`;
      addJson(`${root}/Contents.json`, { info: INFO });
      addJson(`${stack}/Contents.json`, {
        info: INFO,
        layers: ["Front", "Back"].map((part) => ({ filename: `${part}.solidimagestacklayer` })),
      });
      for (const part of ["Front", "Back"]) {
        const layer = `${stack}/${part}.solidimagestacklayer`;
        addJson(`${layer}/Contents.json`, { info: INFO });
        addJson(`${layer}/Content.imageset/Contents.json`, {
          images: [{ filename: `${part}.png`, idiom: "vision", scale: "2x" }],
          info: INFO,
        });
        await png(`${layer}/Content.imageset/${part}.png`, 1024, {
          layer: part === "Front" ? "mark" : "background",
          maskable: part === "Front",
          opaque: part === "Back",
        });
      }
    }

    if (target === "tray") {
      for (const state of STATES) {
        const suffix = state === "ready" ? "" : state[0].toUpperCase() + state.slice(1);
        svg(
          `tray/macos/${name}${suffix}Template.svg`,
          { size: 22, appearance: "light", layer: "mark", purpose: "tray", state },
          { width: 22, height: 22, alpha: true, monochrome: true, template: true },
        );
        for (const points of [16, 18, 22])
          for (const scale of [1, 2]) {
            await png(
              `tray/macos/${points}pt/${name}${suffix}Template${scale === 2 ? "@2x" : ""}.png`,
              points * scale,
              { appearance: "light", purpose: "tray", state, layer: "mark", pointSize: points },
              { monochrome: true, template: true, points, scale },
            );
          }
        for (const ground of ["light", "dark"]) {
          const entries = [];
          for (const size of [16, 20, 24, 32, 40, 48, 64]) {
            const data = await png(`tray/windows/${ground}/png/${state}-${size}.png`, size, {
              appearance: ground,
              purpose: "tray",
              state,
              layer: "mark",
              keyline: true,
            });
            entries.push({ size, data });
          }
          add(`tray/windows/${ground}/${name}-${state}.ico`, encodeIco(entries), {
            sizes: entries.map((entry) => entry.size),
          });
          for (const size of [16, 22, 24, 32, 48])
            await png(`tray/linux/${ground}/${name}-${state}-${size}.png`, size, {
              appearance: ground,
              purpose: "tray",
              state,
              layer: "mark",
              keyline: true,
            });
        }
      }
    }

    if (target === "web") {
      const icons = [];
      for (const size of [16, 32, 48])
        icons.push({
          size,
          data: await png(`web/favicon-${size}x${size}.png`, size, {
            purpose: "favicon",
            shape: source.faviconStyle === "mark" ? "square" : "tile",
          }),
        });
      add("web/favicon.ico", encodeIco(icons), { sizes: [16, 32, 48] });
      svg(
        "web/favicon.svg",
        { size: 32, appearance, purpose: "favicon", layer: "composite", adaptive: true },
        { adaptive: true, vector: true },
      );
      svg(
        "web/safari-pinned-tab.svg",
        { size: 16, appearance: "light", layer: "mark", purpose: "tray", state: "ready" },
        { width: 16, height: 16, monochrome: true, alpha: true, vector: true },
      );
      await png("web/apple-touch-icon.png", 180, { opaque: true });
      const manifestIcons = [];
      for (const size of [192, 512])
        for (const maskable of [false, true]) {
          const filename = `icon-${size}${maskable ? "-maskable" : ""}.png`;
          await png(`web/${filename}`, size, {
            shape: maskable ? "square" : "tile",
            maskable,
            opaque: maskable,
          });
          manifestIcons.push({
            src: filename,
            sizes: `${size}x${size}`,
            type: "image/png",
            purpose: maskable ? "maskable" : "any",
          });
        }
      addJson("web/site.webmanifest", {
        id: "./",
        name: source.name || "VibeField",
        short_name: (source.name || "VibeField").slice(0, 24),
        start_url: "./",
        scope: "./",
        display: "standalone",
        background_color: appearance === "light" ? source.lightGround : source.darkGround,
        theme_color: appearance === "light" ? source.lightGround : source.darkGround,
        icons: manifestIcons,
      });
      add(
        "web/head.html",
        '<!-- Paths assume these assets are copied to your website root. Adjust for a subpath. -->\n<link rel="icon" href="/favicon.ico" sizes="16x16 32x32 48x48">\n<link rel="icon" href="/favicon.svg" type="image/svg+xml" sizes="any">\n<link rel="apple-touch-icon" href="/apple-touch-icon.png" sizes="180x180">\n<link rel="mask-icon" href="/safari-pinned-tab.svg" color="#171719">\n<link rel="manifest" href="/site.webmanifest">\n',
      );
    }

    if (target === "logo") {
      for (const ground of ["light", "dark"]) {
        svg(
          `logo/${name}-mark-${ground}.svg`,
          { size: 1024, appearance: ground, layer: "mark", purpose: "app" },
          { width: 1024, height: 1024, alpha: true, vector: true },
        );
        await png(`logo/${name}-mark-${ground}-1024.png`, 1024, {
          appearance: ground,
          layer: "mark",
        });
        add(`logo/original-living-mark-${ground}.svg`, LIVING[ground], {
          width: 99,
          height: 44,
          original: true,
          animated: true,
          vector: true,
          alpha: true,
        });
      }
    }
    done++;
  }
  addJson("recipe.json", source);
  add("README.md", readme(source, selected, name));
  // The manifest lists the other files, never itself, so byte counts are not self-referential.
  addJson("export-manifest.json", {
    version: 1,
    generator: "VibeField Icon Studio",
    name: source.name,
    style: source.style,
    appearance,
    targets: selected,
    files: assets.slice(),
  });
  progress(`Ready: ${files.length} files`);
  return files;
}

export const bundleZip = (files) => zipStore(files);
