#!/usr/bin/env node
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
// Reuse the repository's installed build tool; no network or extra install is required.
const require = createRequire(
  new URL("../../packages/electron-shell/package.json", import.meta.url),
);
const { build } = require("esbuild");
const living = Object.fromEntries(
  await Promise.all(
    ["light", "dark"].map(async (ground) => [
      ground,
      await readFile(
        join(here, "../../packages/design-kit/src/living-mark", `living-mark-${ground}.svg`),
        "utf8",
      ),
    ]),
  ),
);
await writeFile(
  join(here, "src/living-assets.mjs"),
  `// Generated by build.mjs from the design kit; do not edit.\nexport const LIVING = ${JSON.stringify(living)};\n`,
);
const result = await build({
  entryPoints: [join(here, "src/app.mjs")],
  bundle: true,
  format: "esm",
  target: "es2022",
  write: false,
  minify: false,
  legalComments: "inline",
});
const [template, css] = await Promise.all([
  readFile(join(here, "index.html"), "utf8"),
  readFile(join(here, "src/studio.css"), "utf8"),
]);
const script = result.outputFiles[0].text.replaceAll("</script", "<\\/script");
// Capture a pristine portable source before the application writes blob URLs into the DOM.
const html = template
  .replace("/* STUDIO_STYLE */", () => css)
  .replace(
    "/* STUDIO_SCRIPT */",
    () =>
      `globalThis.__ICON_STUDIO_SOURCE__ = '<!doctype html>\\n' + document.documentElement.outerHTML;\n${script}`,
  );
await mkdir(join(here, "dist"), { recursive: true });
await writeFile(join(here, "dist/index.html"), html);
await writeFile(join(here, "dist/VibeField Icon Studio.html"), html);
console.log(
  `Built ${join(here, "dist/VibeField Icon Studio.html")} (${Math.round(Buffer.byteLength(html) / 1024)} KB; no external requests)`,
);
