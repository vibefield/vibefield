#!/usr/bin/env node
// GT-7 — the Ghostty key catalog Settings → Terminal browses, GENERATED from
// the ghosttea-config crate this repo pins (Cargo.lock), never typed by hand.
//
// The crate is the one authority on both halves: `src/known-keys.txt` is the
// Ghostty key schema ghosttea speaks (202 keys at 0.11.1), and
// `support_for_key` in `src/lib.rs` is its only classification of them
// (applied · parsed · unsupported). The loader's snapshot exposes that
// classification only for keys a document SETS; a page that lists every key
// needs the whole table, so it is generated here and `pnpm gen:check` fails
// the gate when a pin move changes it without a regeneration (EL8: an upgrade
// is an event, and this file says what it changed).
//
//   node scripts/gen-ghostty-keys.mjs           write the module
//   node scripts/gen-ghostty-keys.mjs --check   exit 1 if it would change

import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "packages/field-app/src/panels/terminal/ghostty-keys.generated.ts");

function crateDir() {
  const metadata = JSON.parse(
    execFileSync("cargo", ["metadata", "--format-version", "1", "--locked"], {
      cwd: ROOT,
      encoding: "utf8",
      maxBuffer: 256 * 1024 * 1024,
      stdio: ["ignore", "pipe", "inherit"],
    }),
  );
  const matches = metadata.packages.filter((pkg) => pkg.name === "ghosttea-config");
  if (matches.length !== 1) {
    throw new Error(
      `expected exactly one ghosttea-config in the lockfile, found ${matches.length}`,
    );
  }
  const [pkg] = matches;
  return { dir: dirname(pkg.manifest_path), version: pkg.version };
}

function supportTable(lib) {
  const start = lib.indexOf("fn support_for_key(");
  if (start < 0)
    throw new Error("support_for_key is gone from ghosttea-config — read the new classification");
  const body = lib.slice(start, lib.indexOf("\n}\n", start));
  const arms = new Map();
  for (const arm of body.matchAll(
    /((?:"[a-z0-9-]+"\s*\|?\s*)+)=>\s*ConfigSupport::(Applied|Parsed)/gu,
  )) {
    for (const key of arm[1].matchAll(/"([a-z0-9-]+)"/gu)) arms.set(key[1], arm[2].toLowerCase());
  }
  if (!/_\s*=>\s*ConfigSupport::Unsupported/u.test(body)) {
    throw new Error(
      "support_for_key no longer defaults to Unsupported — read the new classification",
    );
  }
  return arms;
}

function ghosttyVersion(lib) {
  const match = /GHOSTTY_CONFIG_COMPAT_VERSION[^=]*=\s*"([^"]+)"/u.exec(lib);
  if (match === null)
    throw new Error("ghosttea-config no longer names its Ghostty compatibility version");
  return match[1];
}

function render() {
  const { dir, version } = crateDir();
  const keysFile = join(dir, "src/known-keys.txt");
  const libFile = join(dir, "src/lib.rs");
  if (!existsSync(keysFile) || !existsSync(libFile)) {
    throw new Error(`ghosttea-config ${version} has no known-keys.txt/lib.rs at ${dir}`);
  }
  const keys = [
    ...new Set(
      readFileSync(keysFile, "utf8")
        .split(/\r?\n/u)
        .map((line) => line.trim())
        .filter(Boolean),
    ),
  ].sort();
  const lib = readFileSync(libFile, "utf8");
  const support = supportTable(lib);
  for (const key of support.keys()) {
    if (!keys.includes(key))
      throw new Error(`support_for_key names ${key}, which the schema does not know`);
  }
  const rows = keys.map(
    (key) => `  { key: ${JSON.stringify(key)}, support: "${support.get(key) ?? "unsupported"}" },`,
  );
  return `// GENERATED by scripts/gen-ghostty-keys.mjs — do not edit.
// Source: ghosttea-config ${version} (the pinned crate): src/known-keys.txt and
// \`support_for_key\` in src/lib.rs. Regenerate with \`pnpm gen\`.

export type GhosttyKeySupport = "applied" | "parsed" | "unsupported";

export const GHOSTTY_KEYS_SOURCE = {
  crate: "ghosttea-config",
  version: ${JSON.stringify(version)},
  ghostty: ${JSON.stringify(ghosttyVersion(lib))},
} as const;

export const GHOSTTY_KEYS: readonly { key: string; support: GhosttyKeySupport }[] = [
${rows.join("\n")}
];
`;
}

const next = render();
if (process.argv.includes("--check")) {
  const current = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
  if (current !== next) {
    console.error(`${OUT} is stale against the pinned ghosttea-config — run \`pnpm gen\``);
    process.exit(1);
  }
} else {
  writeFileSync(OUT, next);
  console.log(`wrote ${OUT}`);
}
