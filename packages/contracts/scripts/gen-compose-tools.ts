// Emits the compose plane's MCP tool list from src/compose.ts (CP-1b; draft/compose-plane/v2/, CP-L2): every verb that
// has its schemas (COMPOSE_VERB_SCHEMAS), with the description a model reads and its input and output as JSON Schema,
// for fieldd's `vibefield` server to list. fieldd carries no zod-to-JSON-Schema of its own at runtime, so the one
// projection is made here, at gen time, from the one definition:
//   gen/compose-tools.ts — imported by fieldd as `@vibefield/contracts/compose-tools`; under `pnpm gen:check`.
// One formatter per file: this generator. Never edit the output by hand.
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import type { ZodTypeAny } from "zod";
import { zodToJsonSchema } from "zod-to-json-schema";
import { COMPOSE_VERB_SCHEMAS, COMPOSE_VERBS } from "../src/compose";

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, "..");

// Inline, with no `$schema` and no `$ref`: an MCP client reads each tool's schema on its own.
const toSchema = (schema: ZodTypeAny): Record<string, unknown> => {
  const { $schema: _drop, ...rest } = zodToJsonSchema(schema, { $refStrategy: "none" }) as Record<
    string,
    unknown
  >;
  return rest;
};

const schemas = COMPOSE_VERB_SCHEMAS as Record<string, { input: ZodTypeAny; output: ZodTypeAny }>;
const tools = COMPOSE_VERBS.filter((verb) => schemas[verb.name] !== undefined).map((verb) => ({
  name: verb.name,
  description: verb.description,
  readOnly: verb.readOnly,
  inputSchema: toSchema(schemas[verb.name]!.input),
  outputSchema: toSchema(schemas[verb.name]!.output),
}));

const out = [
  "// GENERATED by packages/contracts/scripts/gen-compose-tools.ts from src/compose.ts — do not edit;",
  "// `pnpm --filter @vibefield/contracts gen:schema` rewrites it and `pnpm gen:check` holds it fresh.",
  "",
  "/** The compose plane's MCP tools: each built verb's name, description, and input and output as JSON Schema. */",
  `export const COMPOSE_TOOLS = ${JSON.stringify(tools, null, 2)} as const;`,
  "",
].join("\n");
mkdirSync(join(ROOT, "gen"), { recursive: true });
writeFileSync(join(ROOT, "gen", "compose-tools.ts"), out);
console.log(`compose tools: ${tools.length} verbs → gen/compose-tools.ts`);
