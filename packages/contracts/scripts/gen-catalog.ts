// Emits the agent catalog's two projections from src/agent-catalog.ts (AC-1,
// thinking-ar-agent-catalog.md §3.1):
//   gen/agent-catalog.json          — for readers that cannot import TypeScript
//                                     (scripts/check-agent-catalog.mjs at
//                                     preflight); under `pnpm gen:check`.
//   fixtures/agent-catalog.valid.json — the `agent.catalog` wire shape (EL9),
//                                     which the phone's kit mirrors byte for
//                                     byte (scripts/check-ios-fixtures.mjs);
//                                     test/agent-catalog.test.ts holds it
//                                     equal to the table.
// One formatter per file: this generator. Never edit the outputs by hand.
//
// The gen file (only — the fixture is a wire shape the kit mirrors byte for
// byte, so it stays the table and nothing else) records the sha256 of the
// source it was generated from, LF-normalised (AC-7). The checker recomputes
// it before judging, so `pnpm preflight` / `pnpm catalog:check` refuse to prove
// a table the source no longer says instead of judging the last generated one.
import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { AGENT_CATALOG, AgentCatalogEntry } from "../src/agent-catalog";

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, "..");
const SOURCE = "src/agent-catalog.ts";

const catalog = AgentCatalogEntry.array().parse(AGENT_CATALOG);
const sha256 = createHash("sha256")
  .update(readFileSync(join(ROOT, SOURCE), "utf8").replace(/\r\n/g, "\n"))
  .digest("hex");

const generated = {
  "//": "GENERATED by packages/contracts/scripts/gen-catalog.ts from src/agent-catalog.ts — do not edit; `pnpm --filter @vibefield/contracts gen:schema` rewrites it and `pnpm gen:check` holds it fresh",
  source: { file: SOURCE, sha256 },
  catalog,
};
mkdirSync(join(ROOT, "gen"), { recursive: true });
writeFileSync(join(ROOT, "gen", "agent-catalog.json"), `${JSON.stringify(generated, null, 2)}\n`);
writeFileSync(
  join(ROOT, "fixtures", "agent-catalog.valid.json"),
  `${JSON.stringify({ catalog }, null, 2)}\n`,
);
console.log(
  `agent catalog: ${catalog.length} rows → gen/agent-catalog.json, fixtures/agent-catalog.valid.json`,
);
