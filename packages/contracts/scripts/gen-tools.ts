// Emits the tool plane's served list from src/tools.ts (MT-0; draft/thinking-tool-plane.md §3, MT-L1): every row that
// has its schemas (TOOL_SCHEMAS), with its columns, the description a model reads, all four MCP annotations, and its
// input and output as JSON Schema, for fieldd's `vibefield` server to list by audience. fieldd carries no
// zod-to-JSON-Schema of its own at runtime, so the one projection is made here, at gen time, from the one definition:
//   gen/tools.ts — imported by fieldd as `@vibefield/contracts/tools`; under `pnpm gen:check`.
// (It was gen/compose-tools.ts, CP-1b's projection of compose.ts's verbs, until MT-0 moved them into the catalog.)
// One formatter per file: this generator. Never edit the output by hand.
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import type { ZodTypeAny } from "zod";
import { zodToJsonSchema } from "zod-to-json-schema";
import { TOOL_SCHEMAS, TOOLS, type ToolDef } from "../src/tools";

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, "..");

// Inline, with no `$schema` and no `$ref`: an MCP client reads each tool's schema on its own.
const toSchema = (schema: ZodTypeAny): Record<string, unknown> => {
  const { $schema: _drop, ...rest } = zodToJsonSchema(schema, { $refStrategy: "none" }) as Record<
    string,
    unknown
  >;
  return rest;
};

// All four on every row (the MT lead's ruling of 23:35Z): a client that ignores MCP's "meaningful only when
// readOnlyHint is false" would read a read-only tool as destructive by MCP's default. Every room is closed-world.
const annotations = (row: ToolDef) => ({
  readOnlyHint: row.readOnly,
  destructiveHint: row.readOnly ? false : row.destructive === true,
  idempotentHint: row.readOnly ? true : row.idempotent === true,
  openWorldHint: false,
});

const schemas = TOOL_SCHEMAS as Record<string, { input: ZodTypeAny; output: ZodTypeAny }>;
const tools = TOOLS.filter((row) => schemas[row.name] !== undefined).map((row) => ({
  name: row.name,
  family: row.family,
  category: row.category,
  audience: row.audience,
  scope: row.scope,
  slice: row.slice,
  description: row.description,
  annotations: annotations(row),
  inputSchema: toSchema(schemas[row.name]!.input),
  outputSchema: toSchema(schemas[row.name]!.output),
}));

const out = [
  "// GENERATED by packages/contracts/scripts/gen-tools.ts from src/tools.ts — do not edit;",
  "// `pnpm --filter @vibefield/contracts gen:schema` rewrites it and `pnpm gen:check` holds it fresh.",
  "",
  "/** The tool plane's served rows, in catalog order: each one's columns, description and annotations, and its input",
  " * and output as JSON Schema. A row without schemas is planned and is not here. */",
  `export const SERVED_TOOLS = ${JSON.stringify(tools, null, 2)} as const;`,
  "",
].join("\n");
mkdirSync(join(ROOT, "gen"), { recursive: true });
writeFileSync(join(ROOT, "gen", "tools.ts"), out);
console.log(`tools: ${tools.length} served of ${TOOLS.length} rows → gen/tools.ts`);
