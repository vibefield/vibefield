// @vitest-environment happy-dom

import { execFileSync } from "node:child_process";
import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { LIVING_MARK_SIZE, LIVING_MARK_URL, LivingMark } from "@vibefield/design-kit/living-mark";
import { act, createElement } from "react";
import { createRoot, type Root } from "react-dom/client";
import { afterEach, describe, expect, it } from "vitest";

// DESIGN.md §8 "The living mark, drawn as SVG": the field's own mark, animated, generated from the vendored splash by
// tooling/splash/living-mark.mjs. What a review cannot see by eye is pinned here: the files are the generator's,
// from the bake the boot draws; one drawing on two grounds; the bake's lights and the runtime's clock; at rest under
// reduced motion; and nothing outside itself.

(globalThis as unknown as { IS_REACT_ACT_ENVIRONMENT: boolean }).IS_REACT_ACT_ENVIRONMENT = true;

const REPO_ROOT = join(dirname(fileURLToPath(import.meta.url)), "..", "..", "..");
// The bake, read off the vendored module as glass-look.test.ts reads it: its declaration names only what the boot uses.
const BAKED = JSON.parse(
  readFileSync(
    join(REPO_ROOT, "packages/field-app/src/boot/splash/vibefield-splash.js"),
    "utf8",
  ).match(/^export const BAKED = (\{.*\});$/mu)?.[1] ?? "null",
) as {
  readonly look: { readonly name: string; readonly hash: string };
  readonly phases: {
    readonly livSpeed: number;
    readonly livRoll: number;
    readonly livEdgeSpeed: number;
  };
  readonly mark: { readonly wgsl: string };
};
const DIR = join(REPO_ROOT, "packages/design-kit/src/living-mark");
const file = (ground: "dark" | "light"): string =>
  readFileSync(join(DIR, `living-mark-${ground}.svg`), "utf8");
const css = (svg: string): string => svg.match(/<style>([\s\S]*)<\/style>/u)?.[1] ?? "";

let root: Root | null = null;
let container: HTMLDivElement | null = null;

afterEach(async () => {
  await act(async () => root?.unmount());
  root = null;
  container?.remove();
  container = null;
});

describe("the living mark, drawn as SVG", () => {
  it("is the generator's output from the splash the boot vendors, never a hand edit", () => {
    const out = execFileSync(
      process.execPath,
      [join(REPO_ROOT, "tooling/splash/living-mark.mjs"), "--check"],
      { encoding: "utf8" },
    );
    expect(out).toContain("living mark fresh");
    for (const ground of ["dark", "light"] as const) {
      expect(file(ground)).toContain(
        `<!-- GENERATED by tooling/splash/living-mark.mjs from the vendored splash's look "${BAKED.look.name}" (${BAKED.look.hash}) — do not edit`,
      );
    }
  });

  it("is one drawing on the icon's two grounds: white ink on dark, black on light", () => {
    expect(css(file("dark"))).toContain("var(--vf-mark-ink,#fff)");
    expect(css(file("light"))).toContain("var(--vf-mark-ink,#000)");
    const swapped = file("light")
      .replaceAll("var(--vf-mark-ink,#000)", "var(--vf-mark-ink,#fff)")
      .replace("For a light ground.", "For a dark ground.");
    expect(swapped).toBe(file("dark"));
  });

  it("stands in the kit's box, at the field's own scale", () => {
    const svg = file("dark");
    const { width, height } = LIVING_MARK_SIZE;
    expect(svg).toMatch(new RegExp(`<svg [^>]*width="${width}" height="${height}"`, "u"));
    const box =
      svg
        .match(/viewBox="([^"]+)"/u)?.[1]
        ?.split(" ")
        .map(Number) ?? [];
    expect(box.slice(2)).toEqual([width * 100, height * 100]);
  });

  it("wears the bake's three lights: livRgbEdge's thirds, rose, mint and cobalt", () => {
    const palette = BAKED.mark.wgsl.match(/const K_livCol = array<vec4f, 4>\((.*?)\);/u)?.[1];
    const hex = [...(palette ?? "").matchAll(/vec4f\(([^)]*)\)/gu)].map(
      (m) =>
        `#${(m[1] ?? "")
          .split(",")
          .slice(0, 3)
          .map((v) =>
            Math.round(Number(v) * 255)
              .toString(16)
              .padStart(2, "0"),
          )
          .join("")
          .toUpperCase()}`,
    );
    const strokes = [...file("dark").matchAll(/<g stroke="(#[0-9A-F]{6})"/gu)].map((m) => m[1]);
    expect(strokes).toEqual([hex[0], hex[3], hex[1]]);
    expect(strokes).toEqual(["#FF0054", "#00F59B", "#083CFF"]);
  });

  it("plays the runtime's clock: a twist of two whole turns and a lap of the lights", () => {
    const { livSpeed, livRoll, livEdgeSpeed } = BAKED.phases;
    const twoTurns = (4 * Math.PI) / (livSpeed * livRoll);
    const lap = 1 / Math.abs(livSpeed * livEdgeSpeed * 0.025);
    const style = css(file("dark"));
    for (const name of ["loop", "cover", "hole"])
      expect(style).toContain(`vf-lm-${name} ${+twoTurns.toFixed(4)}s infinite`);
    expect(style).toContain(`vf-lm-twist ${+twoTurns.toFixed(4)}s infinite`);
    expect(style).toContain(`vf-lm-travel ${+lap.toFixed(4)}s linear`);
    expect(style).toContain("animation-composition:replace,add,add");
  });

  it("stands at rest under reduced motion — every animated part", () => {
    const style = css(file("dark"));
    const animated = new Set(
      [...style.matchAll(/\.(vf-lm-\w+)\{animation:vf-/gu)].map((m) => m[1]),
    );
    expect([...animated].sort()).toEqual(["vf-lm-c", "vf-lm-e", "vf-lm-h", "vf-lm-l"]);
    expect(style).toContain(
      "@media (prefers-reduced-motion:reduce){.vf-lm-e,.vf-lm-c,.vf-lm-h,.vf-lm-l{animation:none}}",
    );
  });

  it("needs nothing outside itself, and stays light", () => {
    for (const ground of ["dark", "light"] as const) {
      const svg = file(ground);
      expect(svg).not.toMatch(/<script|<image|<foreignObject|@import|href=/u);
      expect([...svg.matchAll(/url\(([^)]*)\)/gu)].map((m) => m[1])).toEqual(["#vf-lm-x"]);
      expect(Buffer.byteLength(svg)).toBeLessThan(24 * 1024);
    }
  });

  it("is an image of its ground's file, sized by its box, named only when a label asks", async () => {
    container = document.createElement("div");
    document.body.append(container);
    root = createRoot(container);
    await act(async () => {
      root?.render(createElement(LivingMark, { ground: "light", width: 198 }));
    });
    const img = container.querySelector("img");
    expect(img?.getAttribute("src")).toBe(LIVING_MARK_URL.light);
    expect(LIVING_MARK_URL.light).toMatch(/living-mark-light\.svg$/u);
    expect([img?.getAttribute("width"), img?.getAttribute("height")]).toEqual(["198", "88"]);
    expect([img?.getAttribute("alt"), img?.getAttribute("aria-hidden")]).toEqual(["", "true"]);
    await act(async () => {
      root?.render(createElement(LivingMark, { label: "Loading" }));
    });
    const named = container.querySelector("img");
    expect(named?.getAttribute("src")).toBe(LIVING_MARK_URL.dark);
    expect([named?.getAttribute("alt"), named?.getAttribute("aria-hidden")]).toEqual([
      "Loading",
      null,
    ]);
  });
});
