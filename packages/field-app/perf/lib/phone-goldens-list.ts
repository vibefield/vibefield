/** The SDK's test-only entry, reached by dynamic `import()`: wall R8 forbids a static import of it from field-app's
 * production sources (perf/lib is one), and names dynamic `import()` as the sanctioned hatch. */
type SdkTesting = typeof import("@vibefield/puppeteer-view-sdk/testing");
const sdkTesting = (): Promise<SdkTesting> => import("@vibefield/puppeteer-view-sdk/testing");
/** The row's classes that are flags; the one other `is-` class is its status. */
const FLAGS = ["is-active", "is-stale", "is-linked", "is-remote", "is-receded"] as const;
const TEXT_NODE = 3;

const text = (element: Element | null | undefined): string => element?.textContent ?? "";

function agentCell(cell: Element | null): ListAgentCell {
  const host = cell?.querySelector(".vf-monitor-list-host");
  if (host) return { host: text(host) };
  const terminal = cell?.querySelector(".vf-monitor-list-terminal");
  if (terminal) return { terminal: text(terminal) };
  const icon = cell?.querySelector("i");
  const children = [...(cell?.childNodes ?? [])];
  const small = [...(cell?.children ?? [])].find((child) => child.tagName === "SMALL");
  return {
    mark: icon?.querySelector("svg") ? "svg" : text(icon),
    model: children
      .filter((node) => node.nodeType === TEXT_NODE)
      .map((node) => node.textContent ?? "")
      .join(""),
    account: small ? text(small) : null,
  };
}

function rowOf(button: HTMLButtonElement, id: string): ListRowRecord {
  const classes = [...button.classList];
  const has = (name: (typeof FLAGS)[number]): boolean => classes.includes(name);
  const status = classes.find(
    (name) => name.startsWith("is-") && !(FLAGS as readonly string[]).includes(name),
  );
  const project = button.querySelector(".vf-monitor-list-project");
  const branch = project?.querySelector("small");
  return {
    id,
    status: status === undefined ? "" : status.slice("is-".length),
    active: has("is-active"),
    stale: has("is-stale"),
    linked: has("is-linked"),
    remote: has("is-remote"),
    receded: has("is-receded"),
    current: button.getAttribute("aria-current") === "true",
    project: text(project?.querySelector("strong")),
    branch: branch ? text(branch) : null,
    agent: agentCell(button.querySelector(".vf-monitor-list-agent")),
    detail: text(button.querySelector(".vf-monitor-list-detail")),
    context: text(button.querySelector(".vf-monitor-list-context")),
    label: button.getAttribute("aria-label") ?? "",
  };
}

/** One step: the view mounted over its rows, read, every row pressed for its id, then unmounted. */
async function drawn(
  rows: readonly AgentView[],
): Promise<Pick<ListStep, "section" | "toolbar" | "empty" | "rows">> {
  const { countingCommands, fixtureInput, parameterDefaults } = await sdkTesting();
  /** The manifest's own defaults (`list-parameters.js` :1-4): the phone passes none. */
  const parameters = parameterDefaults(listMonitorView.manifest);
  const host = document.createElement("div");
  document.body.append(host);
  const commands = countingCommands();
  let instance: MonitorViewInstance | undefined;
  try {
    await act(async () => {
      instance = listMonitorView.mount(
        host,
        fixtureInput({ agents: rows, parameters }),
        commands.commands,
      );
    });
    const section = host.querySelector("section.vf-monitor-list");
    if (!(section instanceof HTMLElement)) throw new Error("the list drew no section");
    const buttons = [...section.querySelectorAll<HTMLButtonElement>(".vf-monitor-list-row")];
    await act(async () => {
      for (const button of buttons) button.click();
    });
    const ids = [...commands.selects];
    if (ids.length !== buttons.length)
      throw new Error(`${buttons.length} rows drawn, ${ids.length} said whose they are`);
    const empty = section.querySelector(".vf-monitor-list-empty");
    return {
      section: {
        count: text(section.querySelector(".vf-monitor-list-count")),
        allReceded: section.classList.contains("is-all-receded"),
        rowHeight: section.style.getPropertyValue("--mv-list-row-height"),
        projectWidth: section.style.getPropertyValue("--mv-list-project-width"),
      },
      toolbar: text(section.querySelector(".vf-monitor-list-new")),
      empty: empty
        ? { title: text(empty.querySelector("span")), hint: text(empty.querySelector("small")) }
        : null,
      rows: buttons.map((button, index) => rowOf(button, ids[index] ?? "")),
    };
  } finally {
    await act(async () => instance?.unmount());
    host.remove();
  }
}

/** The steps: one per window step, the gap's recorded as a gap. React's act environment is set for this span alone. */
export async function listSteps(input: PhoneViewInput): Promise<ListStep[]> {
  const scope = globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean };
  const was = scope.IS_REACT_ACT_ENVIRONMENT;
  scope.IS_REACT_ACT_ENVIRONMENT = true;
  try {
    const steps: ListStep[] = [];
    for (const step of input.steps) {
      const head = { at: step.at, ...(step.frame === undefined ? {} : { frame: step.frame }) };
      if (step.gap === true) steps.push({ ...head, gap: true });
      else steps.push({ ...head, ...(await drawn(step.rows ?? [])) });
    }
    return steps;
  } finally {
    if (was === undefined) delete scope.IS_REACT_ACT_ENVIRONMENT;
    else scope.IS_REACT_ACT_ENVIRONMENT = was;
  }
}

export const golden: PhoneViewGolden = { note: NOTE, compute: listSteps };
