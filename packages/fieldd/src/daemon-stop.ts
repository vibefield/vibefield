/** bin.ts's stop on a signal or a shutdown request: the daemon stops, then the process exits. */
export function exitAfterStop(
  stop: () => Promise<void>,
  exit: (code: number) => void,
): Promise<void> {
  return stop().finally(() => exit(0));
}
