// THE COMMITTED WORDS' MAKER (the orchestrator's R2 Q1, 2026-10-29 — the pane's scripts/make-head-still.ts is its model) — run
// once, by hand, when what a still's faces say changes (DESIGN.md §9's words, the faces the playground stages, the words' ink
// or their layout):
//
//   pnpm --filter @vibefield/plugin-simulator exec tsx scripts/make-face-words.ts
//
// It draws each face with words a still shows — the product's own `drawWords` (notice-canvas.ts) on a Node canvas
// (`@napi-rs/canvas` — Skia, this package's devDependency and nothing it ships) — writes their runs to src/face-words.gen.ts,
// and formats that file with the repository's biome, so this one command makes the committed bytes. Its bytes are this
// machine's fonts' — Skia answers the words' system stack with the platform's sans (the product's Chromium answers it with
// the system UI font) — so, like a still's golden, the file is made on one host and never re-made over by another; say so in
// the commit that re-makes it. test/face-words.test.ts says when it is stale: a face a still shows whose words nothing
// committed says.

import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { createCanvas } from "@napi-rs/canvas";
import { kindPalette } from "@vibefield/plugin-sdk/desk";
import { productPalette } from "@vibefield/plugin-sdk/testing";
import { FIXTURE_MAC, stagedWords } from "../playground/fixture-mac";
import { deviceName, facePlan, faceWords } from "../src/face";
import { packWords } from "../src/face-words";
import { phoneById, shapeOf } from "../src/law";
import { NOTICE_SCALE, type NoticeSpec, noticeKey } from "../src/notice";
import { drawWords, type WordsContext, wordsBytes } from "../src/notice-canvas";
import { phoneLook } from "../src/theme";

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, "..", "..", "..");
const OUT = join(HERE, "..", "src", "face-words.gen.ts");

/** The words each staged face says, as the phone asks its raster for them — by day and by night (one entry a key). */
const specs = new Map<string, { readonly spec: NoticeSpec; readonly what: string }>();
for (const palette of [productPalette.light, productPalette.dark]) {
  const look = phoneLook(kindPalette(palette));
  for (const staged of FIXTURE_MAC) {
    const model = phoneById(staged.deviceType);
    if (model === undefined)
      throw new Error(`the fixture's Mac stages ${staged.deviceType}, which the catalog lacks`);
    const binding = { deviceType: staged.deviceType, runtime: staged.runtime };
    const plan = facePlan(
      { extra: { simulator: stagedWords(staged.is) } },
      { is: "live" },
      deviceName(binding, model),
      true,
    );
    const said = faceWords(plan, look);
    if (said === undefined) continue;
    const spec: NoticeSpec = { points: shapeOf(model).points, scale: NOTICE_SCALE, ...said };
    specs.set(noticeKey(spec), { spec, what: `${staged.is} on the ${model.name}` });
  }
}

const canvas = createCanvas(1, 1);
const ctx = canvas.getContext("2d") as unknown as WordsContext;
const rows: string[] = [];
let total = 0;
for (const [key, { spec, what }] of specs) {
  const drawn = drawWords(canvas, ctx, spec);
  const runs = Buffer.from(packWords(wordsBytes(ctx, drawn.width, drawn.height))).toString(
    "base64",
  );
  total += runs.length;
  rows.push(
    `  // ${what}: "${spec.words.line}"${spec.words.act === null ? "" : ` · ${spec.words.act}`} — ${drawn.width} × ${drawn.height} texels, ${drawn.lines} line${drawn.lines === 1 ? "" : "s"}
  {
    key: ${JSON.stringify(key)},
    width: ${drawn.width},
    height: ${drawn.height},
    block: ${JSON.stringify(drawn.block)},
    lines: ${drawn.lines},
    runs: ${JSON.stringify(runs)},
  },`,
  );
  console.log(`${what}: ${drawn.width} × ${drawn.height}, ${runs.length} base64 characters`);
}

writeFileSync(
  OUT,
  `// GENERATED by scripts/make-face-words.ts — the committed words a Node still draws (face-words.ts). Do not edit: re-run
//   pnpm --filter @vibefield/plugin-simulator exec tsx scripts/make-face-words.ts
import type { StillWords } from "./face-words";

export const STILL_WORDS: readonly StillWords[] = [
${rows.join("\n")}
];
`,
);
// the repository's formatter, so the command alone makes the committed bytes (no second step to forget)
execFileSync("pnpm", ["exec", "biome", "format", "--write", relative(ROOT, OUT)], {
  cwd: ROOT,
  stdio: "inherit",
});
console.log(`wrote ${relative(ROOT, OUT)} — ${specs.size} faces, ${total} base64 characters`);
