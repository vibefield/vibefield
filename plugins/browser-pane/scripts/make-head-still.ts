// THE COMMITTED HEADS' MAKER (PT-1 ruling 8) — run once, by hand, when what a still's head says changes:
//
//   pnpm --filter @vibefield/plugin-browser-pane exec tsx scripts/make-head-still.ts && pnpm exec biome format --write plugins/browser-pane/src/head-still.gen.ts
//
// It draws each head a Node still shows with the product's own `drawHead` (head-canvas.ts) on a Node canvas
// (`@napi-rs/canvas` — Skia, this package's devDependency and nothing it ships) and writes the runs to
// src/head-still.gen.ts. Its bytes are this machine's fonts' — Skia answers the head's system stack with the platform's
// sans (the product's Chromium answers it with the system UI font) — so, like a still's golden, the file is blessed on
// one host and never re-made over by another; say so in the commit that re-makes it.

import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { createCanvas, ImageData } from "@napi-rs/canvas";
import type { LiveInfo } from "@vibefield/plugin-sdk/desk";
import { cutOf, DEFAULT_DEVICE, type Device, deviceById } from "../src/devices";
import { bandDensity, bandFor, headKey, headStateOf } from "../src/head";
import { drawHead, type HeadContext, headBitmap } from "../src/head-canvas";
import { packRuns } from "../src/head-still";
import { SAMPLE_URL } from "../src/ids";
import { shapeOf } from "../src/law";
import { sampleFavicon } from "../src/sample-page";

/** The still's density: zoom 1 at dpr 2 (the playground's `STILL_DPR`). */
const STILL_ZOOM_DPR = 2;

/** The heads a still draws: the default pane on the sample and on a blank page, a phone's pane on the sample — and (PT-2) the
 * default pane on a live page, its words the face's (the playground's `live` state: playground/live.ts says its address). */
const LIVE_URL = "https://lumen.example/reader";
const HEADS: readonly {
  readonly device: Device;
  readonly url: string;
  readonly info?: LiveInfo;
  readonly what: string;
}[] = [
  { device: DEFAULT_DEVICE, url: SAMPLE_URL, what: "the default pane on the sample" },
  { device: DEFAULT_DEVICE, url: "about:blank", what: "the default pane on a blank page" },
  { device: deviceById("phone") as Device, url: SAMPLE_URL, what: "a phone's pane on the sample" },
  {
    device: DEFAULT_DEVICE,
    url: LIVE_URL,
    info: { address: LIVE_URL },
    what: "the default pane on a live page",
  },
];

const base64 = (bytes: Uint8Array): string => Buffer.from(bytes).toString("base64");

const favicon = createCanvas(64, 64);
favicon
  .getContext("2d")
  .putImageData(new ImageData(new Uint8ClampedArray(sampleFavicon(64)), 64, 64), 0, 0);
const canvas = createCanvas(1, 1);
const ctx = canvas.getContext("2d") as unknown as HeadContext;

const rows: string[] = [];
let total = 0;
for (const { device, url, info, what } of HEADS) {
  // the size a document holds for the device (a new pane's, a device switch's) — what a still spawns, so the keys agree
  const S = shapeOf(cutOf(device), device);
  const st = headStateOf(url, S, info);
  const tpu = bandDensity(S, bandFor(STILL_ZOOM_DPR));
  const fav = st.favicon === "sample" ? (favicon as unknown as CanvasImageSource) : null;
  const { width, height } = drawHead(canvas, ctx, S, st, tpu, fav);
  const bm = headBitmap(ctx, width, height);
  const engraving = base64(packRuns(bm.bytes, 0, width * bm.h, [3]));
  const print = base64(packRuns(bm.bytes, bm.at * width, width * height, [0, 1, 2, 3]));
  total += engraving.length + print.length;
  rows.push(
    `  // ${what}: ${width} × ${height} texels at ${tpu} a world unit\n  {\n    key: ${JSON.stringify(headKey(S, st, tpu))},\n    width: ${width},\n    height: ${height},\n    h: ${bm.h},\n    at: ${bm.at},\n    engraving:\n      ${JSON.stringify(engraving)},\n    print:\n      ${JSON.stringify(print)},\n  },`,
  );
  console.log(
    `${what}: ${width} × ${height}, ${engraving.length + print.length} base64 characters`,
  );
}

const out = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "head-still.gen.ts");
writeFileSync(
  out,
  `// GENERATED by scripts/make-head-still.ts — the committed heads a Node still draws (head-still.ts). Do not edit.
import type { StillHead } from "./head-still";

export const STILL_HEADS: readonly StillHead[] = [
${rows.join("\n")}
];
`,
);
console.log(`wrote ${out} — ${total} base64 characters`);
